"""Is a file generated or vendored? (EVD-1.6, V-7)

A heuristic on the path and the file header. The snapshot table also has flags; a flag set
there wins, so a person can mark a file the heuristic missed. It is a heuristic: a generated
file with no marker and an ordinary path is not caught.
"""

import re
from collections.abc import Mapping
from dataclasses import dataclass

from services.evidence import SnapshotReader, Unresolved

_VENDORED_DIRS = frozenset(
    {"vendor", "vendors", "node_modules", "third_party", "third-party", "bower_components"}
)
_GENERATED_DIRS = frozenset({"generated", "__generated__"})
_GENERATED_HEADER = re.compile(
    r"(?i)\b(auto[- ]?generated|generated by|generated file|do not edit|@generated"
    r"|code generated)\b"
)
_VENDORED_HEADER = re.compile(r"(?i)\bvendored\b")
_HEADER_LINES = 15


@dataclass(frozen=True)
class FileFlags:
    generated: bool = False
    vendored: bool = False


def detect_flags(
    path: str, reader: SnapshotReader, recorded: Mapping[str, FileFlags] | None = None
) -> FileFlags:
    parts = {part.lower() for part in path.split("/")[:-1]}
    generated = bool(parts & _GENERATED_DIRS)
    vendored = bool(parts & _VENDORED_DIRS)
    try:
        header = "\n".join(reader.lines(path)[:_HEADER_LINES])
    except Unresolved:
        header = ""
    generated = generated or _GENERATED_HEADER.search(header) is not None
    vendored = vendored or _VENDORED_HEADER.search(header) is not None
    known = (recorded or {}).get(path)
    if known is not None:
        generated, vendored = generated or known.generated, vendored or known.vendored
    return FileFlags(generated, vendored)
